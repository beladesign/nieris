  document.addEventListener('keydown', event => {
    if (!modal.classList.contains('is-open')) return;
    if (event.key === 'Escape') closeGallery();
    if (event.key === 'ArrowLeft') previous();
    if (event.key === 'ArrowRight') next();
  });
